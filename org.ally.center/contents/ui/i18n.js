function detectarIdioma(localeStr) {
    var code = (localeStr || "en").toLowerCase().substring(0, 2);
    return STRINGS[code] ? code : "en";
}

function tr(lang, key) {
    var dict = STRINGS[lang] || STRINGS["en"];
    return dict[key] || STRINGS["en"][key] || key;
}
